public class PengkondisianIfElseIfElse {
    public static void main(String[] args) {
        int golongan = 5;
        if (golongan == 1) System.out.println("gaji 1 juta");
        else if (golongan == 2) System.out.println("gaji 2 juta");
        else if (golongan == 3) System.out.println("gaji 3 juta");
        else if (golongan == 4) System.out.println("gaji 4 juta");
        else if (golongan == 5) System.out.println("gaji 5 juta");
        else System.out.println("Input Golongan Salah");

    }
}
